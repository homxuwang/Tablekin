CREATE TABLE IF NOT EXISTS public.kitchens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 30),
  description text,
  cover_path text,
  is_public boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.kitchen_invites (
  kitchen_id bigint PRIMARY KEY REFERENCES public.kitchens(id) ON DELETE CASCADE,
  invite_code text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  rotated_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.kitchen_members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
  nickname text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (kitchen_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 20),
  is_public boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.dishes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  category_id bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 40),
  description text,
  recipe text,
  image_path text,
  image_paths text[] NOT NULL DEFAULT '{}',
  tags text[] NOT NULL DEFAULT '{}',
  is_public boolean NOT NULL DEFAULT true,
  is_recipe_public boolean NOT NULL DEFAULT true,
  is_available boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT dishes_tags_valid CHECK (coalesce(array_length(tags, 1), 0) <= 12),
  CONSTRAINT dishes_image_paths_valid CHECK (coalesce(array_length(image_paths, 1), 0) <= 9)
);

CREATE INDEX IF NOT EXISTS dishes_tags_gin ON public.dishes USING gin (tags);
CREATE INDEX IF NOT EXISTS dishes_kitchen_idx ON public.dishes (kitchen_id, sort_order, id);

CREATE TABLE IF NOT EXISTS public.ingredients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(trim(name)) BETWEEN 1 AND 30),
  unit text NOT NULL DEFAULT '份',
  stock numeric NOT NULL DEFAULT 0 CHECK (stock >= 0),
  alert_threshold numeric NOT NULL DEFAULT 0 CHECK (alert_threshold >= 0),
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.dish_ingredients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  dish_id bigint NOT NULL REFERENCES public.dishes(id) ON DELETE CASCADE,
  ingredient_id bigint NOT NULL REFERENCES public.ingredients(id) ON DELETE CASCADE,
  amount numeric NOT NULL CHECK (amount > 0),
  UNIQUE (dish_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  diner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  diner_name text NOT NULL DEFAULT '朋友',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'done', 'rejected', 'cancelled')),
  note text,
  reject_reason text,
  order_date date NOT NULL DEFAULT CURRENT_DATE,
  meal_time_type text NOT NULL DEFAULT 'asap' CHECK (meal_time_type IN ('asap', 'point', 'range')),
  meal_time_start text,
  meal_time_end text,
  acked_at timestamptz,
  decided_at timestamptz,
  done_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_kitchen_status_idx ON public.orders (kitchen_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_diner_idx ON public.orders (diner_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  dish_id bigint REFERENCES public.dishes(id) ON DELETE SET NULL,
  dish_name text NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS public.stock_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  ingredient_id bigint NOT NULL REFERENCES public.ingredients(id) ON DELETE CASCADE,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  order_id bigint REFERENCES public.orders(id) ON DELETE SET NULL,
  mode text NOT NULL DEFAULT 'delta',
  change numeric NOT NULL,
  balance numeric NOT NULL,
  reason text,
  request_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS stock_logs_request_id_uq
  ON public.stock_logs (kitchen_id, request_id)
  WHERE request_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.shortage_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kitchen_id bigint NOT NULL REFERENCES public.kitchens(id) ON DELETE CASCADE,
  owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  diner_name text NOT NULL DEFAULT '朋友',
  dish_name text NOT NULL,
  ingredient_name text NOT NULL,
  needed numeric NOT NULL DEFAULT 0,
  stock numeric NOT NULL DEFAULT 0,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  kitchen_id bigint REFERENCES public.kitchens(id) ON DELETE CASCADE,
  order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE,
  title text NOT NULL,
  body text,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

