CREATE OR REPLACE FUNCTION public.reorder_kitchen_items(
  p_kitchen_id bigint,
  p_kind text,
  p_ids bigint[],
  p_expected_ids bigint[]
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_idx integer;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  IF NOT public.is_kitchen_member(p_kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'not_kitchen_member';
  END IF;
  IF p_kind NOT IN ('categories', 'dishes') THEN
    RAISE EXCEPTION 'sort_kind_invalid';
  END IF;

  IF p_kind = 'categories' THEN
    FOR v_idx IN 1..array_length(p_ids, 1) LOOP
      UPDATE public.categories SET sort_order = v_idx WHERE id = p_ids[v_idx] AND kitchen_id = p_kitchen_id;
    END LOOP;
  ELSE
    FOR v_idx IN 1..array_length(p_ids, 1) LOOP
      UPDATE public.dishes SET sort_order = v_idx WHERE id = p_ids[v_idx] AND kitchen_id = p_kitchen_id;
    END LOOP;
  END IF;

  RETURN jsonb_build_object('ok', true);
END;
$$;

CREATE OR REPLACE FUNCTION public.list_kitchen_tags(p_kitchen_id bigint DEFAULT 0, p_limit integer DEFAULT 60)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  WITH tag_counts AS (
    SELECT t AS tag, count(*)::integer AS dish_count
    FROM public.dishes d, unnest(d.tags) AS t
    WHERE (p_kitchen_id = 0 OR d.kitchen_id = p_kitchen_id)
      AND (
        public.is_kitchen_member(d.kitchen_id)
        OR (d.is_public = true AND EXISTS (SELECT 1 FROM public.kitchens k WHERE k.id = d.kitchen_id AND k.is_public = true))
      )
    GROUP BY t
    ORDER BY dish_count DESC, t ASC
    LIMIT greatest(1, least(coalesce(p_limit, 60), 100))
  )
  SELECT jsonb_build_object(
    'tags', coalesce((SELECT jsonb_agg(jsonb_build_object('tag', tag, 'dish_count', dish_count)) FROM tag_counts), '[]'::jsonb)
  );
$$;

CREATE OR REPLACE FUNCTION public.mark_notifications_read(
  p_ids bigint[] DEFAULT NULL,
  p_kitchen_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_count integer;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  UPDATE public.notifications
  SET is_read = true
  WHERE user_id = v_uid
    AND is_read = false
    AND (p_ids IS NULL OR id = ANY(p_ids))
    AND (p_kitchen_id IS NULL OR kitchen_id = p_kitchen_id);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN jsonb_build_object('marked', v_count);
END;
$$;

