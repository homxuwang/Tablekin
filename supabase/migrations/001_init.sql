CREATE OR REPLACE FUNCTION public.accept_order_atomic(p_order_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_order public.orders%ROWTYPE;
  v_need record;
  v_ing public.ingredients%ROWTYPE;
  v_deducted jsonb := '[]'::jsonb;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'order_not_found'; END IF;
  IF NOT public.is_kitchen_member(v_order.kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'not_kitchen_member';
  END IF;
  IF v_order.status <> 'pending' THEN RAISE EXCEPTION 'order_not_pending'; END IF;

  -- Lock ingredients in deterministic order and verify stock
  FOR v_need IN
    SELECT di.ingredient_id, SUM(di.amount * oi.quantity) AS total_need
    FROM public.order_items oi
    JOIN public.dish_ingredients di ON di.dish_id = oi.dish_id
    WHERE oi.order_id = p_order_id
    GROUP BY di.ingredient_id
    ORDER BY di.ingredient_id
  LOOP
    SELECT * INTO v_ing FROM public.ingredients WHERE id = v_need.ingredient_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'ingredient_missing'; END IF;
    IF v_ing.stock < v_need.total_need THEN
      RAISE EXCEPTION 'ingredient_shortage:%:%:%', v_ing.name, v_ing.stock, v_need.total_need;
    END IF;

    UPDATE public.ingredients SET stock = v_ing.stock - v_need.total_need WHERE id = v_ing.id;

    INSERT INTO public.stock_logs (
      kitchen_id, owner_id, ingredient_id, actor_id, order_id, mode, change, balance, reason
    ) VALUES (
      v_order.kitchen_id, v_order.owner_id, v_ing.id, v_uid, p_order_id,
      'order', -v_need.total_need, v_ing.stock - v_need.total_need,
      '接单扣减（#' || p_order_id || '）'
    );

    v_deducted := v_deducted || jsonb_build_object(
      'ingredient_id', v_ing.id,
      'name', v_ing.name,
      'deducted', v_need.total_need,
      'balance', v_ing.stock - v_need.total_need
    );
  END LOOP;

  UPDATE public.orders
  SET status = 'accepted',
      acked_at = coalesce(acked_at, now()),
      decided_at = now()
  WHERE id = p_order_id;

  IF v_order.diner_id <> v_uid THEN
    INSERT INTO public.notifications (user_id, kitchen_id, order_id, title, body)
    VALUES (v_order.diner_id, v_order.kitchen_id, p_order_id, '大厨已接单，开始做啦', '敬请期待美味出锅');
  END IF;

  RETURN jsonb_build_object('ok', true, 'order_id', p_order_id, 'deducted', v_deducted);
END;
$$;

