CREATE OR REPLACE FUNCTION public.is_kitchen_member(p_kitchen_id bigint, p_user_id uuid DEFAULT auth.uid())
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.kitchen_members
    WHERE kitchen_id = p_kitchen_id AND user_id = p_user_id
  );
$$;

CREATE OR REPLACE FUNCTION public.is_kitchen_owner(p_kitchen_id bigint, p_user_id uuid DEFAULT auth.uid())
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.kitchens
    WHERE id = p_kitchen_id AND owner_id = p_user_id
  );
$$;

CREATE OR REPLACE FUNCTION public.generate_invite_code()
RETURNS text
LANGUAGE sql
AS $$
  SELECT upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 8));
$$;

