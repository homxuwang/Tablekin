CREATE OR REPLACE FUNCTION public.create_kitchen_atomic(
  p_name text,
  p_description text DEFAULT NULL,
  p_is_public boolean DEFAULT true,
  p_cover_path text DEFAULT NULL,
  p_nickname text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_name text := trim(coalesce(p_name, ''));
  v_kitchen_id bigint;
  v_code text;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  IF v_name = '' THEN RAISE EXCEPTION 'kitchen_name_required'; END IF;
  IF char_length(v_name) > 30 THEN RAISE EXCEPTION 'kitchen_name_too_long'; END IF;

  INSERT INTO public.kitchens (owner_id, name, description, is_public, cover_path)
  VALUES (v_uid, v_name, nullif(trim(coalesce(p_description, '')), ''), coalesce(p_is_public, true), p_cover_path)
  RETURNING id INTO v_kitchen_id;

  INSERT INTO public.kitchen_members (kitchen_id, user_id, role, nickname)
  VALUES (v_kitchen_id, v_uid, 'owner', coalesce(nullif(trim(coalesce(p_nickname, '')), ''), '主厨'));

  v_code := public.generate_invite_code();
  INSERT INTO public.kitchen_invites (kitchen_id, invite_code)
  VALUES (v_kitchen_id, v_code);

  RETURN jsonb_build_object(
    'ok', true,
    'kitchen_id', v_kitchen_id,
    'name', v_name,
    'invite_code', v_code
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.get_kitchen_invite(p_kitchen_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_row public.kitchen_invites%ROWTYPE;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.kitchens WHERE id = p_kitchen_id) THEN
    RAISE EXCEPTION 'kitchen_not_found';
  END IF;
  IF NOT public.is_kitchen_owner(p_kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'not_kitchen_owner';
  END IF;

  SELECT * INTO v_row FROM public.kitchen_invites WHERE kitchen_id = p_kitchen_id;
  IF NOT FOUND THEN
    INSERT INTO public.kitchen_invites (kitchen_id, invite_code)
    VALUES (p_kitchen_id, public.generate_invite_code())
    RETURNING * INTO v_row;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'kitchen_id', v_row.kitchen_id,
    'invite_code', v_row.invite_code,
    'created_at', v_row.created_at,
    'rotated_at', v_row.rotated_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.reset_kitchen_invite(p_kitchen_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_row public.kitchen_invites%ROWTYPE;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  IF NOT public.is_kitchen_owner(p_kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'not_kitchen_owner';
  END IF;

  UPDATE public.kitchen_invites
  SET invite_code = public.generate_invite_code(), rotated_at = now()
  WHERE kitchen_id = p_kitchen_id
  RETURNING * INTO v_row;

  IF NOT FOUND THEN
    INSERT INTO public.kitchen_invites (kitchen_id, invite_code, rotated_at)
    VALUES (p_kitchen_id, public.generate_invite_code(), now())
    RETURNING * INTO v_row;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'rotated', true,
    'kitchen_id', v_row.kitchen_id,
    'invite_code', v_row.invite_code,
    'created_at', v_row.created_at,
    'rotated_at', v_row.rotated_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.join_kitchen_by_code(code text, nick text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_kitchen_id bigint;
  v_kitchen_name text;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;

  SELECT ki.kitchen_id, k.name INTO v_kitchen_id, v_kitchen_name
  FROM public.kitchen_invites ki
  JOIN public.kitchens k ON k.id = ki.kitchen_id
  WHERE upper(ki.invite_code) = upper(trim(coalesce(code, '')));

  IF v_kitchen_id IS NULL THEN
    RAISE EXCEPTION 'invite_code_not_found';
  END IF;

  INSERT INTO public.kitchen_members (kitchen_id, user_id, role, nickname)
  VALUES (v_kitchen_id, v_uid, 'member', coalesce(nullif(trim(coalesce(nick, '')), ''), '家人'))
  ON CONFLICT (kitchen_id, user_id) DO UPDATE
  SET nickname = COALESCE(NULLIF(trim(EXCLUDED.nickname), ''), public.kitchen_members.nickname);

  RETURN jsonb_build_object(
    'ok', true,
    'kitchen_id', v_kitchen_id,
    'kitchen_name', v_kitchen_name
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.adjust_stock_atomic(
  p_ingredient_id bigint,
  p_mode text,
  p_value numeric,
  p_reason text DEFAULT NULL,
  p_expected_stock numeric DEFAULT NULL,
  p_request_id text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_ing public.ingredients%ROWTYPE;
  v_existing public.stock_logs%ROWTYPE;
  v_before numeric;
  v_after numeric;
  v_change numeric;
  v_owner_id uuid;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  IF p_mode NOT IN ('delta', 'recount') THEN RAISE EXCEPTION 'mode_invalid'; END IF;
  IF p_value IS NULL OR p_value < 0 OR (p_mode = 'delta' AND p_value = 0) THEN
    RAISE EXCEPTION 'value_invalid';
  END IF;

  SELECT * INTO v_ing FROM public.ingredients WHERE id = p_ingredient_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'ingredient_not_found'; END IF;
  IF NOT public.is_kitchen_member(v_ing.kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'not_kitchen_member';
  END IF;

  IF p_request_id IS NOT NULL AND trim(p_request_id) <> '' THEN
    SELECT * INTO v_existing FROM public.stock_logs
    WHERE kitchen_id = v_ing.kitchen_id AND request_id = trim(p_request_id);
    IF FOUND THEN
      RETURN jsonb_build_object(
        'ok', true,
        'ingredient_id', v_existing.ingredient_id,
        'mode', v_existing.mode,
        'change', v_existing.change,
        'balance', v_existing.balance,
        'replayed', true
      );
    END IF;
  END IF;

  v_before := v_ing.stock;
  IF p_mode = 'delta' THEN
    v_change := p_value;
    v_after := v_before + v_change;
  ELSE
    IF p_expected_stock IS NULL THEN RAISE EXCEPTION 'expected_stock_required'; END IF;
    IF v_before <> p_expected_stock THEN
      RAISE EXCEPTION 'stock_changed:%:%', v_before, p_expected_stock;
    END IF;
    v_after := p_value;
    v_change := v_after - v_before;
    IF v_change = 0 THEN RAISE EXCEPTION 'no_change'; END IF;
  END IF;

  IF v_after < 0 THEN RAISE EXCEPTION 'stock_negative'; END IF;
  IF v_after > 1000000 THEN RAISE EXCEPTION 'stock_too_large'; END IF;

  SELECT owner_id INTO v_owner_id FROM public.kitchens WHERE id = v_ing.kitchen_id;

  UPDATE public.ingredients SET stock = v_after WHERE id = v_ing.id;

  INSERT INTO public.stock_logs (
    kitchen_id, owner_id, ingredient_id, actor_id, mode, change, balance, reason, request_id
  ) VALUES (
    v_ing.kitchen_id, v_owner_id, v_ing.id, v_uid, p_mode, v_change, v_after,
    coalesce(nullif(trim(coalesce(p_reason, '')), ''), CASE WHEN p_mode = 'delta' THEN '手动入库' ELSE '库存盘点' END),
    nullif(trim(coalesce(p_request_id, '')), '')
  );

  RETURN jsonb_build_object(
    'ok', true,
    'ingredient_id', v_ing.id,
    'ingredient_name', v_ing.name,
    'unit', v_ing.unit,
    'mode', p_mode,
    'change', v_change,
    'balance', v_after,
    'balance_before', v_before,
    'replayed', false
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.create_order_atomic(
  p_kitchen_id bigint,
  p_items jsonb,
  p_note text DEFAULT NULL,
  p_diner_name text DEFAULT NULL,
  p_meal_time_type text DEFAULT 'asap',
  p_meal_time_start text DEFAULT NULL,
  p_meal_time_end text DEFAULT NULL,
  p_order_date date DEFAULT CURRENT_DATE
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_kitchen public.kitchens%ROWTYPE;
  v_order_id bigint;
  v_item jsonb;
  v_dish public.dishes%ROWTYPE;
  v_qty integer;
  v_member record;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'not_signed_in'; END IF;
  SELECT * INTO v_kitchen FROM public.kitchens WHERE id = p_kitchen_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'kitchen_not_found'; END IF;
  IF NOT v_kitchen.is_public AND NOT public.is_kitchen_member(p_kitchen_id, v_uid) THEN
    RAISE EXCEPTION 'kitchen_not_visible';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'order_items_required';
  END IF;
  IF p_order_date < CURRENT_DATE THEN RAISE EXCEPTION 'order_date_past'; END IF;
  IF p_order_date > CURRENT_DATE + 365 THEN RAISE EXCEPTION 'order_date_invalid'; END IF;
  IF p_meal_time_type = 'asap' AND p_order_date <> CURRENT_DATE THEN
    RAISE EXCEPTION 'asap_requires_today';
  END IF;

  INSERT INTO public.orders (
    kitchen_id, owner_id, diner_id, diner_name, note,
    order_date, meal_time_type, meal_time_start, meal_time_end
  ) VALUES (
    p_kitchen_id, v_kitchen.owner_id, v_uid,
    coalesce(nullif(trim(coalesce(p_diner_name, '')), ''), '朋友'),
    nullif(trim(coalesce(p_note, '')), ''),
    p_order_date, p_meal_time_type, p_meal_time_start, p_meal_time_end
  ) RETURNING id INTO v_order_id;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_qty := coalesce((v_item->>'quantity')::integer, 0);
    IF v_qty <= 0 THEN RAISE EXCEPTION 'quantity_invalid'; END IF;
    SELECT * INTO v_dish FROM public.dishes WHERE id = (v_item->>'dish_id')::bigint;
    IF NOT FOUND OR v_dish.kitchen_id <> p_kitchen_id THEN
      RAISE EXCEPTION 'dish_not_in_kitchen';
    END IF;
    IF NOT v_dish.is_available THEN
      RAISE EXCEPTION 'dish_not_orderable:%', v_dish.name;
    END IF;

    INSERT INTO public.order_items (order_id, dish_id, dish_name, quantity)
    VALUES (v_order_id, v_dish.id, v_dish.name, v_qty);
  END LOOP;

  -- Notify kitchen members (best-effort)
  FOR v_member IN SELECT user_id FROM public.kitchen_members WHERE kitchen_id = p_kitchen_id AND user_id <> v_uid LOOP
    INSERT INTO public.notifications (user_id, kitchen_id, order_id, title, body)
    VALUES (
      v_member.user_id, p_kitchen_id, v_order_id,
      coalesce(nullif(trim(coalesce(p_diner_name, '')), ''), '朋友') || ' 刚点了菜',
      '去「订单」看看想吃什么'
    );
  END LOOP;

  RETURN jsonb_build_object('ok', true, 'order_id', v_order_id);
END;
$$;

